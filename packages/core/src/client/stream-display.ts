export function streamDisplayUnit(name: string, stored: string): string {
  return stored.trim() ? stored : Object.hasOwn(fallbackUnits, name) ? fallbackUnits[name]! : '';
}

export function streamDisplayValue(name: string, value: number): number {
  if ((name === 'pressure' || name === 'pressure_hpa') && value < 10000) return value * 100;
  if (name === 'uv') return value / 227;
  return value;
}
